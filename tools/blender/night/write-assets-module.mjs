// Writes src/shared/NightAssets.luau from tools/blender/night/manifest.json (sizes, mesh parts) and
// tools/blender/night/uploaded.json (asset ids from upload-assets.mjs; optional: without it every
// id is nil and the game keeps its current visuals).
//
//   node tools/blender/night/write-assets-module.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, "tools/blender/night/manifest.json"), "utf8"));
const uploadedPath = path.join(ROOT, "tools/blender/night/uploaded.json");
const uploaded = fs.existsSync(uploadedPath) ? JSON.parse(fs.readFileSync(uploadedPath, "utf8")) : {};

const id = (v) => {
	if (v === null || v === undefined) return "nil";
	if (!Number.isSafeInteger(v) || v <= 0) throw new Error(`bad asset id ${v}`);
	return String(v);
};

const lines = [
	"--!strict",
	"-- GENERATED by tools/blender/night/write-assets-module.mjs from manifest.json and uploaded.json.",
	"-- Do not edit by hand. Custom Blender models for Hundred Demon Night (docs/assets/register.md).",
	"-- size: measured Roblox size in studs (x, y, z); parts: mesh names inside the uploaded model;",
	"-- model: Model asset id (InsertService:LoadAsset); decal / texture: Decal and Image asset ids.",
	"-- root: blade root relative to the `_blade` mesh centre, in studs, for lining up swapped blades.",
	"-- A nil model id means not uploaded yet: the game keeps its current visual for that asset.",
	"",
	"export type Asset = { size: { number }, parts: { string }, model: number?, decal: number?, texture: number?, root: { number }? }",
	"",
	"local NightAssets: { [string]: Asset } = {",
];
for (const [name, entry] of Object.entries(manifest)) {
	const u = uploaded[name] ?? {};
	const parts = Object.keys(entry.parts).map((p) => `"${p}"`).join(", ");
	lines.push(`\t${name} = {`);
	lines.push(`\t\tsize = { ${entry.size_studs.join(", ")} },`);
	lines.push(`\t\tparts = { ${parts} },`);
	lines.push(`\t\tmodel = ${id(u.model)},`);
	lines.push(`\t\tdecal = ${id(u.decal)},`);
	lines.push(`\t\ttexture = ${id(u.texture)},`);
	if (entry.root) lines.push(`\t\troot = { ${entry.root.join(", ")} },`);
	lines.push("\t},");
}
lines.push("}", "", "return NightAssets", "");

const out = path.join(ROOT, "src/shared/NightAssets.luau");
fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${path.relative(ROOT, out)} (${Object.keys(manifest).length} assets, ${Object.keys(uploaded).length} uploaded)`);
