// Writes src/shared/<Game>Assets.luau from tools/blender/<game>/manifest.json (sizes, mesh parts,
// glow colours) and tools/blender/<game>/uploaded.json (asset ids from upload-assets.mjs; optional:
// without it every id is nil and the game keeps its current visuals).
//
//   node tools/blender/write-assets-module.mjs <night|spire|garden>

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const GAMES = { night: ["NightAssets", "Hundred Demon Night"], spire: ["SpireAssets", "Neon Spire"], garden: ["GardenAssets", "Egg Garden"] };
const game = process.argv[2] ?? "night";
if (!GAMES[game]) throw new Error(`unknown game ${game}; use ${Object.keys(GAMES).join(", ")}`);
const [moduleName, label] = GAMES[game];
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, `tools/blender/${game}/manifest.json`), "utf8"));
const uploadedPath = path.join(ROOT, `tools/blender/${game}/uploaded.json`);
const uploaded = fs.existsSync(uploadedPath) ? JSON.parse(fs.readFileSync(uploadedPath, "utf8")) : {};

const id = (v) => {
	if (v === null || v === undefined) return "nil";
	if (!Number.isSafeInteger(v) || v <= 0) throw new Error(`bad asset id ${v}`);
	return String(v);
};

const lines = [
	"--!strict",
	`-- GENERATED by tools/blender/write-assets-module.mjs ${game} from manifest.json and uploaded.json.`,
	`-- Do not edit by hand. Custom Blender models for ${label} (docs/assets/register.md).`,
	"-- size: measured Roblox size in studs (x, y, z); parts: mesh names inside the uploaded model;",
	"-- model: Model asset id (InsertService:LoadAsset); decal / texture: Decal and Image asset ids.",
	"-- A nil model id means not uploaded yet: the game keeps its current visual for that asset.",
	...(game === "spire" ? ["-- glow: sRGB Neon colour per glow mesh (left untextured, set to Neon by Models.luau)."] : []),
	"",
	game === "spire"
		? "export type Asset = {\n\tsize: { number },\n\tparts: { string },\n\tglow: { [string]: { number } },\n\tmodel: number?,\n\tdecal: number?,\n\ttexture: number?,\n}"
		: "export type Asset = { size: { number }, parts: { string }, model: number?, decal: number?, texture: number? }",
	"",
	`local ${moduleName}: { [string]: Asset } = {`,
];
for (const [name, entry] of Object.entries(manifest)) {
	const u = uploaded[name] ?? {};
	const parts = Object.keys(entry.parts).map((p) => `"${p}"`).join(", ");
	lines.push(`\t${name} = {`);
	lines.push(`\t\tsize = { ${entry.size_studs.join(", ")} },`);
	lines.push(`\t\tparts = { ${parts} },`);
	if (game === "spire") {
		lines.push("\t\tglow = {");
		for (const [p, c] of Object.entries(entry.glow ?? {})) lines.push(`\t\t\t${p} = { ${c.join(", ")} },`);
		lines.push("\t\t},");
	}
	lines.push(`\t\tmodel = ${id(u.model)},`);
	lines.push(`\t\tdecal = ${id(u.decal)},`);
	lines.push(`\t\ttexture = ${id(u.texture)},`);
	lines.push("\t},");
}
lines.push("}", "", `return ${moduleName}`, "");

const out = path.join(ROOT, `src/shared/${moduleName}.luau`);
fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${path.relative(ROOT, out)} (${Object.keys(manifest).length} assets, ${Object.keys(uploaded).length} uploaded)`);
