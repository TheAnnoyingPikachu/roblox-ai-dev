"""Writes src/stations-client/FoeAnchors.luau: the points each Shadow Legion enemy's power move (FoePowers) casts
from, measured on its built model (assets/stations/<asset>.fbx), as the concepts picked them (decision 0105).

blender --background --factory-startup --python tools/blender/stations/foe_anchors.py

An anchor is its bone and its offset from that bone's rest head, in studs at the built size, in the Root's axes
(x right, y up, -z forward). Its point: "tip" the vertex of a bone's part farthest from the bone's head (a blade's
point), "top" the part's highest vertex, "centroid" the part's middle, "bone" the bone's head itself, "mouth" midway
between the jaw's farthest vertex and the head's frontmost. Run it again when an enemy's model is rebuilt."""
import json
import math
import os

import bpy
from mathutils import Vector

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
OUT = os.path.join(ROOT, "src", "stations-client", "FoeAnchors.luau")

ANCHORS = {
    "foe_knight_forge": {"blade": ("tip", "elbow_r")},
    "foe_archer_forge": {"arrow": ("tip", "arrow"), "bow": ("tip", "elbow_l")},
    "foe_knight_shield_forge": {"shield": ("centroid", "elbow_l")},
    "foe_ogre_forge": {"club": ("tip", "elbow_r")},
    "foe_mage_forge": {"hand": ("top", "elbow_r")},  # the top of its staff
    "foe_knight_berserker_forge": {"bl": ("tip", "elbow_l"), "br": ("tip", "elbow_r")},
    "foe_mage_priest_forge": {"staff": ("bone", "tip")},
    "foe_archer_crossbow_forge": {"bow": ("tip", "elbow_r")},
    "foe_cavalry_forge": {"lance": ("tip", "elbow_r")},
    "foe_mage_necromancer_forge": {"skull": ("tip", "elbow_l")},
    "foe_ogre_commander_forge": {"axe": ("tip", "weapon")},
    "foe_knight_shield_commander_forge": {"sword": ("tip", "weapon"), "shield": ("centroid", "elbow_l")},
    "foe_golem_forge": {"castle": ("top", "body"), "fl": ("tip", "elbow_l"), "fr": ("tip", "elbow_r")},
    "foe_cavalry_commander_forge": {"sword": ("tip", "elbow_r")},
    "foe_dragon_drake_forge": {"mouth": ("mouth", "head")},
    "foe_dragon_forge": {"mouth": ("mouth", "head")},
    "foe_dragon_alpha_forge": {"mouth": ("mouth", "head")},
}


def num(x):
    s = f"{x:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


lines = []
for asset in sorted(ANCHORS):
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.import_scene.fbx(filepath=os.path.join(ROOT, "assets", "stations", f"{asset}.fbx"), axis_forward="-Z", axis_up="Y",
                             primary_bone_axis="Y", secondary_bone_axis="X")
    arm = next(o for o in bpy.data.objects if o.type == "ARMATURE")
    mesh = max((o for o in bpy.data.objects if o.type == "MESH"), key=lambda o: len(o.data.vertices))
    bpy.context.view_layer.update()
    co = [mesh.matrix_world @ v.co for v in mesh.data.vertices]
    studs = json.load(open(os.path.join(ROOT, "tools", "blender", "stations", "manifest.json"), encoding="utf-8"))[asset]["size_studs"]
    unit = (max(p.z for p in co) - min(p.z for p in co)) / studs[1]  # Blender units a built stud

    def head(b):
        return arm.matrix_world @ arm.data.bones[b].head_local

    def group(g):
        gi = mesh.vertex_groups[g].index
        return [v.index for v in mesh.data.vertices if any(x.group == gi and x.weight >= 0.5 for x in v.groups)]

    def root(v):  # a Blender offset -> the Root's axes, studs (the model faces -Y, its right is -X)
        return (-v.x / unit, v.z / unit, v.y / unit)

    out = []
    for name, (kind, b) in sorted(ANCHORS[asset].items()):
        if kind == "tip":
            p = co[max(group(b), key=lambda i: (co[i] - head(b)).length)]
        elif kind == "top":
            p = co[max(group(b), key=lambda i: co[i].z)]
        elif kind == "centroid":
            vs = group(b)
            p = sum((co[i] for i in vs), Vector()) / len(vs)
        elif kind == "bone":
            p = head(b)
        else:  # mouth
            jaw = co[max(group("jaw"), key=lambda i: (co[i] - head("jaw")).length)]
            snout = co[min(group("head"), key=lambda i: co[i].y)]
            p = (jaw + snout) / 2
        d = root(p - head(b))
        assert all(math.isfinite(x) for x in d), (asset, name)
        out.append(f'\t\t{name} = {{ "{b}", {{ {", ".join(num(x) for x in d)} }} }},')
    lines += [f"\t{asset} = {{", *out, "\t},"]

head_text = """--!strict
-- Generated by tools/blender/stations/foe_anchors.py from the built enemy models: do not edit by hand.
-- Where each enemy's power move (FoePowers) casts from: by name, a bone and the point's offset from that bone's rest
-- head, in studs at the built size, in the Root's axes (x right, y up, -z forward). Pure data.

return {
"""
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(head_text + "\n".join(lines) + "\n} :: { [string]: { [string]: { any } } }\n")
print("ANCHORS", len(ANCHORS), OUT)
