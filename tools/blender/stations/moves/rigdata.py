"""Writes src/shared/AnimalRig.luau from the built skinned animal models: for each, its size, its bones' rest heads,
the points its feet stand on, and the anchor points the spells cast from (Spells in stations-client).

blender --background --factory-startup --python rigdata.py -- <repo to write> <repo with the built models> <asset>...

Everything is in studs, in the Root's axes (x right, y up, -z forward), measured from the body bone's rest head.
An anchor is the vertex render_magic.py tracks (the nose: the head's frontmost; the horn: the highest of the head's
front 30 %; ...), given as its bone and its offset from that bone's head. A foot's points are its lowest vertices'
extremes (toe, heel, both sides, the lowest)."""
import os
import sys

import numpy as np
from mathutils import Vector

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rig as R  # noqa: E402

args = sys.argv[sys.argv.index("--") + 1 :]
repo, R.ROOT, assets = args[0], args[1], sorted(args[2:])
LEGS = ("leg_fl", "leg_fr", "leg_bl", "leg_br")


def num(x):
    s = f"{x:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def vec(v):
    return "{ " + ", ".join(num(x) for x in v) + " }"


out = []
for asset in assets:
    r = R.Rig(asset)
    U = r.unit
    rest = r.points()
    lo, hi = rest.min(0), rest.max(0)
    groups = {g.index: g.name for g in r.body.vertex_groups}
    top = []
    for v in r.body.data.vertices:
        ws = sorted(((g.weight, groups[g.group]) for g in v.groups), reverse=True)
        top.append(ws[0][1] if ws else "body")
    top = np.array(top)
    M = r.arm.matrix_world
    heads = {pb.name: M @ pb.bone.head_local for pb in r.arm.pose.bones}
    origin = heads["body"]

    def root(v):  # a Blender offset -> the Root's axes, studs
        return (-v[0] / U, v[2] / U, v[1] / U)

    def rel(p):  # a Blender point -> from the body's head
        return root(Vector(p) - origin)

    def pick(group, score):
        idx = np.nonzero(top == group)[0]
        if len(idx) == 0:
            idx = np.arange(len(rest))
        return int(idx[np.argmax(score(rest[idx]))])

    head = rest[top == "head"] if (top == "head").any() else rest
    hy0 = head[:, 1].min()
    hlen = head[:, 1].max() - hy0
    front = lambda p: np.where(p[:, 1] < hy0 + 0.3 * hlen, p[:, 2], -1e9)  # noqa: E731
    body_mid = rest[top == "body"].mean(0)
    picks = {
        "nose": pick("head", lambda p: -p[:, 1]),
        "crown": pick("head", lambda p: p[:, 2]),
        "horn": pick("head", front),
        "trunk": pick("head", lambda p: -p[:, 2] - 0.3 * p[:, 1]),
        "paw_l": pick("leg_fl", lambda p: -p[:, 2]),
        "paw_r": pick("leg_fr", lambda p: -p[:, 2]),
        "wing_l": pick("leg_bl", lambda p: p[:, 0]),
        "wing_r": pick("leg_br", lambda p: -p[:, 0]),
        "tail": pick("tail", lambda p: np.linalg.norm(p - body_mid, axis=1)),
        "back": pick("body", lambda p: p[:, 2]),
        "chest": pick("body", lambda p: -p[:, 1] - 0.2 * np.abs(p[:, 0])),
    }
    feet = ("leg_fl", "leg_fr") if "flamingo" in asset else LEGS
    if r.upright:
        feet = ("leg_bl", "leg_br")
    lines = [f"\t{asset} = {{"]
    lines.append(f"\t\tsize = {vec(root(Vector((hi - lo).tolist())))},".replace("-", ""))
    lines.append(f"\t\tmid = {vec(rel(((lo + hi) / 2).tolist()))},")
    lines.append(f"\t\tupright = {'true' if r.upright else 'false'},")
    lines.append("\t\tjoints = {")
    for name in sorted(heads):
        lines.append(f"\t\t\t{name} = {vec(rel(heads[name]))},")
    lines.append("\t\t},")
    lines.append("\t\tfeet = {")
    for leg in feet:
        pts = rest[top == leg]
        low = pts[pts[:, 2] < pts[:, 2].min() + 0.12 * (pts[:, 2].max() - pts[:, 2].min())]
        chosen = {int(np.argmin(low[:, 2])), int(np.argmin(low[:, 0])), int(np.argmax(low[:, 0])),
                  int(np.argmin(low[:, 1])), int(np.argmax(low[:, 1]))}
        lines.append(f"\t\t\t{leg} = {{ " + ", ".join(vec(rel(low[i].tolist())) for i in sorted(chosen)) + " },")
    lines.append("\t\t},")
    lines.append("\t\tanchors = {")
    for name, i in picks.items():
        bone = top[i] if top[i] in heads else "body"
        lines.append(f'\t\t\t{name} = {{ "{bone}", {vec(root(Vector(rest[i].tolist()) - heads[bone]))} }},')
    lines.append("\t\t},")
    lines.append("\t},")
    out.append("\n".join(lines))
    print("RIG", asset, "upright" if r.upright else "", feet)

src = f'''--!strict
-- Generated by tools/blender/stations/moves/rigdata.py from the built skinned animal models: do not edit by hand.
-- For each model: its size, its bones' rest heads, the points its feet stand on and the anchor points its spells
-- cast from. Studs at its built size, in the Root's axes (x right, y up, -z forward), from the body bone's rest head;
-- an anchor is its bone and its offset from that bone's head. Pure data: Creatures.client and Spells read it.

export type Point = {{ number }}
export type Model = {{
	size: Point,
	mid: Point,
	upright: boolean,
	joints: {{ [string]: Point }},
	feet: {{ [string]: {{ Point }} }},
	anchors: {{ [string]: {{ any }} }},
}}

local AnimalRig = {{}}

AnimalRig.MODELS = {{
{chr(10).join(out)}
}} :: {{ [string]: Model }}

return AnimalRig
'''
open(os.path.join(repo, "src", "shared", "AnimalRig.luau"), "w", encoding="utf-8", newline="\n").write(src)
print("DONE", len(assets))
