"""Writes src/shared/AnimalMoves.luau: SHANNON's picked idles, attacks and power attacks (2026-11-21) from the concepts.

python export_moves.py <repo>

The attack and power keys are the concepts' own (concepts.py, magic.py), not the fitted ones: the game now lifts a
skinned body by however far a pose pushes its feet under the ground (AnimalRig's feet), as the renders were fitted.
The idles are written in Luau below, line for line from concepts.py."""
import os
import sys
import types

sys.modules["mathutils"] = types.SimpleNamespace(Vector=lambda *a, **k: None)  # magic.py's spells are not run here
sys.modules["fxkit"] = types.SimpleNamespace(bez=None, ease=None, env=None, mix=None, seg=None)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import concepts as C  # noqa: E402
import magic as M  # noqa: E402

repo = sys.argv[1]
PICKS = {  # species: (attack, power)
    "jackal": ("b_leap", "m_pack"), "tortoise": ("a_snap", "m_nova"), "meerkat": ("a_combo", "m_sunorb"),
    "cheetah": ("a_trip", "m_blades"), "rhino": ("a_gore", "m_lance"), "flamingo": ("b_lash", "m_darts"),
    "lion": ("a_maul", "m_roar"), "giraffe": ("a_neck", "m_lance"), "elephant": ("a_tusk", "m_orb"),
}
VARIANTS = {  # a variant's spell, by its asset (each variant keeps its species' idle and attack)
    "creature_jackal_pharaoh_forge": "m_anubis", "creature_jackal_sphinx_forge": "m_sand",
    "creature_tortoise_gemshell_forge": "m_gems", "creature_tortoise_island_forge": "m_surge",
    "creature_meerkat_star_forge": "m_comet", "creature_meerkat_storm_forge": "m_ufo",
    "creature_cheetah_lightning_forge": "m_chain", "creature_cheetah_thunder_forge": "m_thunder",
    "creature_rhino_lava_forge": "m_magma", "creature_rhino_crystal_forge": "m_prism",
    "creature_flamingo_peacock_forge": "m_fan", "creature_flamingo_phoenix_forge": "m_firebird",
    "creature_lion_sun_forge": "m_solar", "creature_lion_shadow_forge": "m_claws",
    "creature_giraffe_acacia_forge": "m_thorns", "creature_giraffe_diamond_forge": "m_prison",
    "creature_elephant_frost_forge": "m_tomb", "creature_elephant_war_forge": "m_axe",
}


def num(x):
    s = f"{round(x, 3):.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def pose(p, ind):
    if not p:
        return "{}"
    order = ["body", "head", "leg_fl", "leg_fr", "leg_bl", "leg_br", "tail"]
    parts = []
    for j in sorted(p, key=lambda j: order.index(j) if j in order else 99):
        v = list(p[j])
        while len(v) > 1 and v[-1] == 0:
            v.pop()
        parts.append(f"{ind}\t{j} = {{ {', '.join(num(x) for x in v)} }},")
    return "{\n" + "\n".join(parts) + f"\n{ind}}}"


def keys(ks, ind):
    rows = []
    for t, p in ks:
        rows.append(f"{ind}\t{{ {num(t)}, {pose(p, ind + chr(9))} }},")
    return "{\n" + "\n".join(rows) + f"\n{ind}}}"


def label(asset_or_species, key):
    if key.startswith("m_"):
        spec = M.CONCEPTS[asset_or_species if asset_or_species.startswith("creature_") else f"creature_{asset_or_species}_forge"][1]
        return spec[key][0], spec[key][2]
    item = C.CONCEPTS[f"creature_{asset_or_species}_forge"][1]["attack"][key]
    return item[0], item[2]


attacks, powers = [], []
for sp, (a, p) in PICKS.items():
    name, ks = label(sp, a)
    assert abs(ks[-1][0] - 0.95) < 1e-9, (sp, a)
    attacks.append(f"\t-- {name}\n\t{sp} = {keys(ks, chr(9))},")
    name, ks = label(sp, p)
    assert abs(ks[-1][0] - 1.6) < 1e-9, (sp, p)
    powers.append(f"\t-- {name}\n\t{sp} = {keys(ks, chr(9))},")
for asset, p in VARIANTS.items():
    sp = asset.split("_")[1]
    name, ks = label(asset, p)
    if ks is label(sp, PICKS[sp][1])[1]:
        powers.append(f"\t-- {name}: its species' own moves")
        continue
    powers.append(f"\t-- {name}\n\t{asset} = {keys(ks, chr(9))},")

IDLES = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "idles.luau"), encoding="utf-8").read()
src = f'''--!strict
-- The animals' moves (SHANNON's picks, 2026-11-21): an idle, an attack and a power attack (a spell) for each species,
-- and a spell of its own for each variant. Pure data and pose functions; Creatures.client plays
-- them and Spells (stations-client) draws the spells' magic. The attack and power keys are generated by
-- tools/blender/stations/moves/export_moves.py from the concepts there (concepts.py, magic.py): change them there.
--
-- A pose is {{ joint = {{ pitch, yaw, roll (degrees), x, y, z (studs at Scale 1) }} }}, as in Creatures.client: positive
-- pitch lifts the nose or swings a foot (an upright animal's arm) forward, a negative tail pitch raises the tail,
-- positive yaw turns left, positive roll swings a hanging leg's foot to the animal's right (a flamingo's wings are its
-- back legs: leg_bl lifts with +roll, leg_br with -roll). Attacks are 0.95 s with the hit at 0.44 s, power attacks
-- 1.6 s with the impact at 0.92 s. Keys may push the feet under the ground: the game lifts the body.

export type Pose = {{ [string]: {{ number }} }}
export type Keys = {{ {{ any }} }}

local AnimalMoves = {{}}

{IDLES}
-- Attacks by species (a variant plays its species')
AnimalMoves.ATTACKS = {{
{chr(10).join(attacks)}
}} :: {{ [string]: Keys }}

-- Power attacks by species, and by asset for a variant whose spell moves differently
AnimalMoves.POWERS = {{
{chr(10).join(powers)}
}} :: {{ [string]: Keys }}

return AnimalMoves
'''
open(os.path.join(repo, "src", "shared", "AnimalMoves.luau"), "w", encoding="utf-8", newline="\n").write(src)
print("written", len(src))
